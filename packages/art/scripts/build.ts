/** Writes the generated SVGs and assets.json (run after adding species): pnpm art:build */
import { mkdirSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { creatureSvg, hintMarkerSvg, markerSvg } from '../src/creature';
import { allSpeciesIds, artInput } from '../src/inputs';
import { BADGE_REGIONS, badgeSvg } from '../src/badges';
import { stampSvg, STAMP_KINDS } from '../src/stamps';
import { FONTS, type AssetEntry } from '../src/manifest';

const root = (p: string) => fileURLToPath(new URL(`../${p}`, import.meta.url));
mkdirSync(root('generated/sprites'), { recursive: true });
mkdirSync(root('generated/markers'), { recursive: true });
mkdirSync(root('generated/stamps'), { recursive: true });
mkdirSync(root('generated/badges'), { recursive: true });

const AUTHOR = 'Odense Monster League (generated by packages/art)';
const assets: AssetEntry[] = [];
for (const id of allSpeciesIds()) {
  const input = artInput(id);
  writeFileSync(root(`generated/sprites/${id}.svg`), creatureSvg(input) + '\n');
  writeFileSync(root(`generated/markers/${id}.svg`), markerSvg(input) + '\n');
  for (const kind of ['sprite', 'marker'] as const) {
    assets.push({
      file: `generated/${kind}s/${id}.svg`,
      kind,
      species: id,
      source: 'code',
      author: AUTHOR,
      licence: 'own',
      placeholder: true,
    });
  }
}
writeFileSync(root('generated/hint.svg'), hintMarkerSvg() + '\n');
assets.push({
  file: 'generated/hint.svg',
  kind: 'hint',
  species: null,
  source: 'code',
  author: AUTHOR,
  licence: 'own',
  placeholder: true,
});
const extra = (file: string, kind: AssetEntry['kind'], svg: string) => {
  writeFileSync(root(file), svg + '\n');
  assets.push({
    file,
    kind,
    species: null,
    source: 'code',
    author: AUTHOR,
    licence: 'own',
    placeholder: true,
  });
};
for (const kind of STAMP_KINDS) {
  extra(`generated/stamps/${kind}.svg`, 'stamp', stampSvg(kind));
  extra(`generated/stamps/${kind}_done.svg`, 'stamp', stampSvg(kind, true));
}
for (let arena = 1; arena <= 8; arena++) {
  for (const region of BADGE_REGIONS) {
    extra(`generated/badges/${region}_badge${arena}.svg`, 'badge', badgeSvg(arena, true, region));
    extra(
      `generated/badges/${region}_badge${arena}_empty.svg`,
      'badge',
      badgeSvg(arena, false, region),
    );
  }
}
writeFileSync(root('assets.json'), JSON.stringify({ assets, fonts: FONTS }, null, 2) + '\n');
console.log(
  `Wrote ${assets.length} assets (${allSpeciesIds().length} species × sprite + marker, 1 hint, ${STAMP_KINDS.length * 2} stamps, ${BADGE_REGIONS.length * 16} badges).`,
);
